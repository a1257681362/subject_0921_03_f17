-- =====================================================================
-- V3 增量：演出票附件（客服整批 ZIP 下载，ticket-2）
-- ---------------------------------------------------------------------
-- 附件二进制存服务端受管目录（storage_name 为服务端生成的 UUID，
-- 原始中文文件名只存库、不参与路径拼接，防路径穿越）；本表只存元数据。
-- 一包最多 50 份的限制在应用层（evops.attachment.zip-max-files）拦截，
-- 按票号归档查询走 (ticket_no, id) 索引。
--
-- 并跑期约定：与 V2 一致，向旧台账 t_evops_schema_version 双写
-- flyway-3，供 SchemaHistoryReconciler 逐版本对账。
-- =====================================================================

CREATE TABLE IF NOT EXISTS t_ticket_attachment (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id     BIGINT NOT NULL,
    ticket_no     VARCHAR(48)  NOT NULL,
    file_name     VARCHAR(255) NOT NULL,
    content_type  VARCHAR(128),
    file_size     BIGINT NOT NULL,
    storage_name  VARCHAR(64)  NOT NULL,
    sha256        VARCHAR(64),
    remark        VARCHAR(255),
    operator      VARCHAR(64)  NOT NULL DEFAULT 'system',
    request_id    VARCHAR(64),
    biz_time      TIMESTAMP,
    version       INT NOT NULL DEFAULT 0,
    deleted       BIGINT NOT NULL DEFAULT 0,
    create_by     BIGINT,
    create_time   TIMESTAMP,
    update_by     BIGINT,
    update_time   TIMESTAMP,
    CONSTRAINT uk_ticket_attach_storage UNIQUE (storage_name)
);

-- 按票号列出附件 / 批量打包按票号取文件的主索引
CREATE INDEX IF NOT EXISTS idx_t_attach_ticket ON t_ticket_attachment (ticket_no, id);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('flyway-3', '演出票附件：元数据表 + 按票号索引，支撑客服整批 ZIP 流式下载（单包上限 50 份）');
