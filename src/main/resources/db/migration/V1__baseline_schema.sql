-- =====================================================================
-- V1 基线：EVOPS 现有库全量快照（base-0 + ticket-1 + auth-1 + checkin-1 + agent-1）
-- ---------------------------------------------------------------------
-- 本脚本对应手工 SQL 时代 src/main/resources/schema.sql 的最终状态。
-- 已有库（含 t_evops_schema_version 的现场库）首飞时通过
-- baseline-on-migrate + baseline-version=1 将本版本记为基线、不再重复执行；
-- 全新环境从头执行本脚本 + 后续增量，一键建到最新。
-- 此后任何 schema 变更只允许新增 V<n> 脚本，严禁修改本文件。
-- =====================================================================

-- 旧版手工变更台账（并跑期保留，与 flyway_schema_history 对账；切旧后可下线）
CREATE TABLE IF NOT EXISTS t_evops_schema_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no VARCHAR(32) NOT NULL,
    description VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_evops_schema_version UNIQUE (version_no)
);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('base-0', 'EVOPS 初始工作区');

-- ============ ticket-1 场馆票务底账 ============

-- 座位主数据
CREATE TABLE IF NOT EXISTS t_seat (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue       VARCHAR(128) NOT NULL,
    area        VARCHAR(64)  NOT NULL,
    row_no      VARCHAR(16)  NOT NULL,
    seat_no     VARCHAR(16)  NOT NULL,
    remark      VARCHAR(255),
    operator    VARCHAR(64)  NOT NULL DEFAULT 'system',
    request_id  VARCHAR(64),
    biz_time    TIMESTAMP,
    version     INT NOT NULL DEFAULT 0,
    deleted     BIGINT NOT NULL DEFAULT 0,
    create_by   BIGINT,
    create_time TIMESTAMP,
    update_by   BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_t_seat_location UNIQUE (venue, area, row_no, seat_no, deleted)
);

-- 演出场次
CREATE TABLE IF NOT EXISTS t_show_session (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    show_name    VARCHAR(128) NOT NULL,
    session_code VARCHAR(32)  NOT NULL,
    venue        VARCHAR(128) NOT NULL,
    show_time    TIMESTAMP,
    status       VARCHAR(16)  NOT NULL DEFAULT 'OPEN',
    remark       VARCHAR(255),
    operator     VARCHAR(64)  NOT NULL DEFAULT 'system',
    request_id   VARCHAR(64),
    biz_time     TIMESTAMP,
    version      INT NOT NULL DEFAULT 0,
    deleted      BIGINT NOT NULL DEFAULT 0,
    create_by    BIGINT,
    create_time  TIMESTAMP,
    update_by    BIGINT,
    update_time  TIMESTAMP,
    CONSTRAINT uk_t_show_session_code UNIQUE (session_code, deleted)
);
CREATE INDEX IF NOT EXISTS idx_t_show_session_venue ON t_show_session (venue);

-- 售票单（主）
CREATE TABLE IF NOT EXISTS t_sale_order (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no     VARCHAR(48) NOT NULL,
    session_id   BIGINT NOT NULL,
    ticket_count INT NOT NULL DEFAULT 0,
    total_amount DECIMAL(10,2) NOT NULL DEFAULT 0,
    status       VARCHAR(16) NOT NULL DEFAULT 'ISSUED',
    operator     VARCHAR(64) NOT NULL DEFAULT 'system',
    request_id   VARCHAR(64),
    biz_time     TIMESTAMP,
    version      INT NOT NULL DEFAULT 0,
    deleted      BIGINT NOT NULL DEFAULT 0,
    create_by    BIGINT,
    create_time  TIMESTAMP,
    update_by    BIGINT,
    update_time  TIMESTAMP,
    CONSTRAINT uk_t_sale_order_no UNIQUE (order_no)
);
CREATE INDEX IF NOT EXISTS idx_t_sale_order_session ON t_sale_order (session_id);

-- 票明细（从）
CREATE TABLE IF NOT EXISTS t_ticket (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_no   VARCHAR(48) NOT NULL,
    order_id    BIGINT NOT NULL,
    session_id  BIGINT NOT NULL,
    seat_id     BIGINT NOT NULL,
    price       DECIMAL(10,2) NOT NULL DEFAULT 0,
    status      VARCHAR(16) NOT NULL DEFAULT 'SOLD',
    operator    VARCHAR(64) NOT NULL DEFAULT 'system',
    request_id  VARCHAR(64),
    biz_time    TIMESTAMP,
    version     INT NOT NULL DEFAULT 0,
    deleted     BIGINT NOT NULL DEFAULT 0,
    create_by   BIGINT,
    create_time TIMESTAMP,
    update_by   BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_t_ticket_no UNIQUE (ticket_no)
);
CREATE INDEX IF NOT EXISTS idx_t_ticket_order ON t_ticket (order_id);
CREATE INDEX IF NOT EXISTS idx_t_ticket_session_status ON t_ticket (session_id, status);
CREATE INDEX IF NOT EXISTS idx_t_ticket_seat ON t_ticket (seat_id);

-- 有效座位占用（退票/作废后物理删除即释放座次）
CREATE TABLE IF NOT EXISTS t_session_seat_occupy (
    session_id  BIGINT NOT NULL,
    seat_id     BIGINT NOT NULL,
    ticket_id   BIGINT NOT NULL,
    order_id    BIGINT NOT NULL,
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_t_session_seat PRIMARY KEY (session_id, seat_id)
);

-- 票状态流水（正向 + 反向追溯链）
CREATE TABLE IF NOT EXISTS t_ticket_status_flow (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id        BIGINT NOT NULL,
    order_id         BIGINT NOT NULL,
    session_id       BIGINT NOT NULL,
    record_type      VARCHAR(16) NOT NULL,
    reverse_flag     INT NOT NULL DEFAULT 0,
    origin_record_id BIGINT,
    from_status      VARCHAR(16),
    to_status        VARCHAR(16),
    reason           VARCHAR(255),
    operator         VARCHAR(64) NOT NULL DEFAULT 'system',
    request_id       VARCHAR(64),
    biz_time         TIMESTAMP,
    create_time      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_t_flow_ticket ON t_ticket_status_flow (ticket_id, id);
CREATE INDEX IF NOT EXISTS idx_t_flow_origin ON t_ticket_status_flow (origin_record_id);

-- 每场次票号顺序号计数
CREATE TABLE IF NOT EXISTS t_ticket_no_alloc (
    session_id  BIGINT PRIMARY KEY,
    cur_val     BIGINT NOT NULL DEFAULT 0,
    update_time TIMESTAMP
);

-- 写请求幂等占坑/快照
CREATE TABLE IF NOT EXISTS t_idempotent_request (
    request_id        VARCHAR(64) PRIMARY KEY,
    request_path      VARCHAR(128),
    request_hash      VARCHAR(64),
    status            VARCHAR(16) NOT NULL,
    business_key      VARCHAR(128),
    response_snapshot CLOB,
    operator          VARCHAR(64),
    create_time       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finish_time       TIMESTAMP
);

-- ============ auth-1 场馆后台 JWT 双令牌认证 ============
-- 整改要求：访问令牌短期有效；刷新令牌服务端存证、轮换一次性使用；登出/改密拉黑在用令牌；改密全端下线。

-- 后台账号（场馆岗位账号，密码只存 PBKDF2 派生哈希）
CREATE TABLE IF NOT EXISTS t_admin_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(64)  NOT NULL,
    display_name  VARCHAR(64)  NOT NULL,
    venue         VARCHAR(128),
    role          VARCHAR(32)  NOT NULL DEFAULT 'STAFF',
    password_hash VARCHAR(255) NOT NULL,
    token_version INT NOT NULL DEFAULT 0,
    status        VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    create_time   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_t_admin_user_username UNIQUE (username)
);

-- 刷新令牌服务端存证（只存 SHA-256 哈希，不存明文）
-- status: ACTIVE 可轮换 / USED 已被一次性消费 / REVOKED 登出·改密·家族连坐撤销
CREATE TABLE IF NOT EXISTS t_refresh_token (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash      VARCHAR(64)  NOT NULL,
    user_id         BIGINT NOT NULL,
    family_id       VARCHAR(64)  NOT NULL,
    token_version   INT NOT NULL DEFAULT 0,
    status          VARCHAR(16)  NOT NULL,
    expires_at      TIMESTAMP NOT NULL,
    create_time     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    rotate_time     TIMESTAMP,
    revoke_time     TIMESTAMP,
    CONSTRAINT uk_t_refresh_token_hash UNIQUE (token_hash)
);
CREATE INDEX IF NOT EXISTS idx_t_refresh_user ON t_refresh_token (user_id);
CREATE INDEX IF NOT EXISTS idx_t_refresh_family ON t_refresh_token (family_id, id);

-- 访问令牌黑名单（登出/改密时按 jti 拉黑；过期行由清理任务清除）
CREATE TABLE IF NOT EXISTS t_token_blacklist (
    jti         VARCHAR(64) PRIMARY KEY,
    user_id     BIGINT NOT NULL,
    reason      VARCHAR(32) NOT NULL,
    expires_at  TIMESTAMP NOT NULL,
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_t_blacklist_expires ON t_token_blacklist (expires_at);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('auth-1', '场馆后台 JWT 双令牌：访问令牌短有效期 + 刷新令牌轮换一次性 + 登出改密拉黑 + 改密全端下线');

-- ============ checkin-1 检票排期（按时间区间预约） ============
-- 预约以 [start_time, end_time) 半开区间存储；同一座位区间重叠或首尾间隔不足 20 分钟均判冲突。
-- status: ACTIVE 有效 / CANCELLED 已取消（取消立即释放，可在该座位再次预约；历史行保留追溯）。
CREATE TABLE IF NOT EXISTS t_checkin_appointment (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_no  VARCHAR(48) NOT NULL,
    seat_id         BIGINT NOT NULL,
    visitor_name    VARCHAR(64),
    contact         VARCHAR(64),
    start_time      TIMESTAMP NOT NULL,
    end_time        TIMESTAMP NOT NULL,
    status          VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    cancel_reason   VARCHAR(255),
    operator        VARCHAR(64)  NOT NULL DEFAULT 'system',
    request_id      VARCHAR(64),
    biz_time        TIMESTAMP,
    version         INT NOT NULL DEFAULT 0,
    deleted         BIGINT NOT NULL DEFAULT 0,
    create_by       BIGINT,
    create_time     TIMESTAMP,
    update_by       BIGINT,
    update_time     TIMESTAMP,
    CONSTRAINT uk_t_checkin_appt_no UNIQUE (appointment_no)
);
-- 占用查询/冲突检测主索引：按座位取候选区间；状态与时间入复合索引便于范围过滤
CREATE INDEX IF NOT EXISTS idx_t_checkin_seat_time
    ON t_checkin_appointment (seat_id, status, start_time, end_time);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('checkin-1', '检票排期：区间预约、重叠/20分钟缓冲冲突、取消即释放、座位占用查询、空档推荐');

-- ============ agent-1 代理售票平台 XML 报文对接 ============
-- 收发原文一律留档、按票号归档可回查；出站失败可重试（退避重试，耗尽置 FAILED 人工介入）。
-- direction: OUTBOUND 场馆->平台（出票/检票/退票/作废通知） / INBOUND 平台->场馆（回调同步）
-- status:
--   OUTBOUND: PENDING 待发送 / SUCCESS 已成功送达 / RETRYING 退避重试中 / FAILED 重试耗尽
--   INBOUND : SUCCESS 已受理处理 / IGNORED 重复 messageId 幂等忽略
-- message_type: TICKET_ISSUE / TICKET_CHECK / TICKET_REFUND / TICKET_VOID / TICKET_QUERY / ACK
CREATE TABLE IF NOT EXISTS t_agent_message (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id      VARCHAR(64) NOT NULL,
    direction       VARCHAR(8)  NOT NULL,
    message_type    VARCHAR(32) NOT NULL,
    ticket_no       VARCHAR(48),
    order_no        VARCHAR(48),
    session_code    VARCHAR(32),
    correlation_id  VARCHAR(64),
    endpoint        VARCHAR(255),
    http_status     INT,
    payload         CLOB NOT NULL,
    status          VARCHAR(16) NOT NULL,
    retry_count     INT NOT NULL DEFAULT 0,
    max_retry       INT NOT NULL DEFAULT 5,
    next_retry_time TIMESTAMP,
    last_error      VARCHAR(2000),
    operator        VARCHAR(64) NOT NULL DEFAULT 'system',
    request_id      VARCHAR(64),
    biz_time        TIMESTAMP,
    create_time     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time     TIMESTAMP,
    CONSTRAINT uk_agent_message_id UNIQUE (message_id, direction)
);
-- 按票号归档回查主索引
CREATE INDEX IF NOT EXISTS idx_agent_msg_ticket ON t_agent_message (ticket_no, id);
-- 重试扫描：出站待处理 + 到期时间
CREATE INDEX IF NOT EXISTS idx_agent_msg_retry
    ON t_agent_message (direction, status, next_retry_time);
CREATE INDEX IF NOT EXISTS idx_agent_msg_type ON t_agent_message (message_type, id);

-- 解析失败/校验失败/业务失败统一进异常清单，保留原文可回查、可人工标记处理。
-- error_type: PARSE_ERROR XML 无法解析 / VALIDATION_ERROR 字段不合规 / BIZ_ERROR 业务处理失败（票状态机等）
-- status: OPEN 待处理 / RESOLVED 已处理 / IGNORED 已忽略
CREATE TABLE IF NOT EXISTS t_agent_parse_error (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    direction      VARCHAR(8)  NOT NULL,
    error_type     VARCHAR(24) NOT NULL,
    message_id     VARCHAR(64),
    ticket_no      VARCHAR(48),
    message_type   VARCHAR(32),
    payload        CLOB,
    error_detail   VARCHAR(2000),
    status         VARCHAR(16) NOT NULL DEFAULT 'OPEN',
    resolve_remark VARCHAR(255),
    operator       VARCHAR(64),
    request_id     VARCHAR(64),
    create_time    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolve_time   TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_agent_err_status ON t_agent_parse_error (status, id);
CREATE INDEX IF NOT EXISTS idx_agent_err_ticket ON t_agent_parse_error (ticket_no, id);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('agent-1', '代理售票平台 XML 对接：Jackson XML 双向映射、收发原文按票号归档、解析失败异常清单、出站失败退避重试');

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('ticket-1', '场馆票务底账：座位/场次/售票单/票/占用/流水/票号分配/幂等');
