-- =====================================================================
-- V5 增量：检票数据出系统统一脱敏（mask-1）
-- ---------------------------------------------------------------------
-- 安全组要求：检票单据（观众姓名/联系方式等敏感字段）出系统一律打码，
-- 仅白名单场务角色可看完整值。规则按版本发布、历史版本留档可追溯；
-- 白名单角色看到明文的每一次都落留痕表，事后可审计「谁、何时、因何接口、
-- 看了哪条业务数据的什么敏感项」。
--
-- 表：
--   t_mask_rule_version  脱敏规则版本（每发布一次新版本 +1，旧版置 SUPERSEDED 留档）
--   t_sensitive_view_log 敏感字段明文查看留痕（白名单角色放行时逐字段落痕）
--
-- 数据：
--   1) 初始规则版本 v=1：姓名按 NAME、联系方式按 CONTACT 打码，白名单 STAGE_STAFF/ADMIN；
--   2) 旧库场务样本账号 stage01 角色由 STAFF 细化为 STAGE_STAFF（新库 seeder 已同步）。
--
-- 幂等响应快照在服务端始终存完整值（内部存证），回放时按「当次请求人角色」重新
-- 套规则脱敏：非白名单不能借重放看到明文，白名单重放同样留痕（见 MaskService）。
--
-- 并跑期约定：与 V2~V4 一致，向旧台账 t_evops_schema_version 双写
-- flyway-5，供 SchemaHistoryReconciler 逐版本对账。
-- =====================================================================

-- 脱敏规则版本：规则变更只追加新版本，不改写历史行；同版本号唯一。
-- status: ACTIVE 当前唯一生效版本 / SUPERSEDED 已被新版本取代（留档）
CREATE TABLE IF NOT EXISTS t_mask_rule_version (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_version    INT NOT NULL,
    rule_code       VARCHAR(64) NOT NULL DEFAULT 'CHECKIN_DEFAULT',
    -- 敏感字段 -> 打码类型，JSON 形如 {"visitorName":"NAME","contact":"CONTACT"}
    field_rules     CLOB NOT NULL,
    -- 可见完整值的白名单角色，逗号分隔，如 STAGE_STAFF,ADMIN
    whitelist_roles VARCHAR(255) NOT NULL,
    status          VARCHAR(16) NOT NULL,
    remark          VARCHAR(255),
    operator        VARCHAR(64) NOT NULL DEFAULT 'system',
    request_id      VARCHAR(64),
    biz_time        TIMESTAMP,
    create_time     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time     TIMESTAMP,
    CONSTRAINT uk_mask_rule_version UNIQUE (rule_version)
);
-- 当前生效版本查询：status=ACTIVE（全表仅一行）
CREATE INDEX IF NOT EXISTS idx_mask_rule_status ON t_mask_rule_version (status, rule_version);

-- 敏感数据明文查看留痕：白名单角色每次看到完整值逐字段落一行，只追加不修改。
CREATE TABLE IF NOT EXISTS t_sensitive_view_log (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL,
    username        VARCHAR(64) NOT NULL,
    role_code       VARCHAR(48) NOT NULL,
    -- 业务数据类型（如 CheckinAppointment）与主键/业务号（如预约号），定位"看了哪条"
    biz_type        VARCHAR(64) NOT NULL,
    biz_id          VARCHAR(96),
    -- 字段名与打码类型（visitorName/NAME）；命中的规则版本与放行原因
    field_name      VARCHAR(64) NOT NULL,
    mask_type       VARCHAR(32) NOT NULL,
    rule_version    INT NOT NULL,
    channel         VARCHAR(16) NOT NULL,
    request_path    VARCHAR(255) NOT NULL,
    request_id      VARCHAR(64),
    view_time       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- 按人审计 / 按业务数据回查 两条主路径
CREATE INDEX IF NOT EXISTS idx_senslog_user ON t_sensitive_view_log (username, view_time, id);
CREATE INDEX IF NOT EXISTS idx_senslog_biz ON t_sensitive_view_log (biz_type, biz_id, view_time);

-- 旧库：场务样本账号角色细化（新库由 seeder 直接播 STAGE_STAFF）。
UPDATE t_admin_user SET role = 'STAGE_STAFF' WHERE username = 'stage01' AND role = 'STAFF';

-- 初始生效规则版本 v=1。
MERGE INTO t_mask_rule_version (id, rule_version, rule_code, field_rules, whitelist_roles,
                                status, remark, operator, biz_time)
KEY (rule_version)
VALUES (1, 1, 'CHECKIN_DEFAULT',
        '{"visitorName":"NAME","contact":"CONTACT"}',
        'STAGE_STAFF,ADMIN',
        'ACTIVE',
        '检票单据脱敏初始规则：观众姓名/联系方式出系统打码，场务与管理员可见完整值',
        'system', CURRENT_TIMESTAMP);
-- 上面显式插入 id=1 不会推进 IDENTITY 序列（GENERATED BY DEFAULT），
-- 发布新版本前必须把序列拨到 2，否则首次发布自增 id 仍为 1 撞主键。
ALTER TABLE t_mask_rule_version ALTER COLUMN id RESTART WITH 2;

