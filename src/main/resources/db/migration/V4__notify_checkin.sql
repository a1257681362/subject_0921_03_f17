-- =====================================================================
-- V4 增量：检票关键节点通知场务（notify-1）
-- ---------------------------------------------------------------------
-- 票状态变更（检票等关键节点）在事务提交后按事件触发，模板变量渲染成
-- 现场可用的文案，经「站内信 + 邮件」双通道发给场务；每次发送逐通道
-- 落发送记录，渲染后标题/正文在记录里快照留档，事后改模板不影响已发内容。
--
-- 表：
--   t_notify_template   通知模板（按 事件+通道 维度，改动 version+1）
--   t_notify_recipient  场务收件人（工号关联后台账号看站内信；邮箱走邮件）
--   t_notify_dispatch   一次事件触发的一个通知批次（汇总通道成败）
--   t_notify_record     逐通道发送记录（渲染快照/状态/重试，可统计可回查）
--   t_inbox_message     站内信箱（场务登录后按工号查收、标记已读）
--
-- 并跑期约定：与 V2/V3 一致，向旧台账 t_evops_schema_version 双写
-- flyway-4，供 SchemaHistoryReconciler 逐版本对账。
-- =====================================================================

-- 通知模板：template_code+channel 唯一；同一事件可分别配站内信/邮件两套文案。
-- 内容修改只追加版本号（version+1），发送记录快照当时的 version 与渲染结果。
CREATE TABLE IF NOT EXISTS t_notify_template (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_code  VARCHAR(48) NOT NULL,
    template_name  VARCHAR(96) NOT NULL,
    event_code     VARCHAR(48) NOT NULL,
    channel        VARCHAR(8)  NOT NULL,
    title_template VARCHAR(255) NOT NULL,
    body_template  CLOB NOT NULL,
    enabled        INT NOT NULL DEFAULT 1,
    tpl_version    INT NOT NULL DEFAULT 1,
    status         VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    remark         VARCHAR(255),
    operator       VARCHAR(64) NOT NULL DEFAULT 'system',
    request_id     VARCHAR(64),
    biz_time       TIMESTAMP,
    version        INT NOT NULL DEFAULT 0,
    deleted        BIGINT NOT NULL DEFAULT 0,
    create_by      BIGINT,
    create_time    TIMESTAMP,
    update_by      BIGINT,
    update_time    TIMESTAMP,
    CONSTRAINT uk_notify_tpl_code_channel UNIQUE (template_code, channel, deleted)
);
-- 事件触发时按 event_code 取启用模板
CREATE INDEX IF NOT EXISTS idx_notify_tpl_event ON t_notify_template (event_code, enabled, id);

-- 场务收件人：staff_no 与后台登录名一致（用于站内信箱），email 用于邮件通道；
-- 只有邮箱的外部协作人员 staff_no 可空。
CREATE TABLE IF NOT EXISTS t_notify_recipient (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_name VARCHAR(64) NOT NULL,
    staff_no       VARCHAR(64),
    email          VARCHAR(128),
    role_code      VARCHAR(48) NOT NULL DEFAULT 'STAGE_STAFF',
    enabled        INT NOT NULL DEFAULT 1,
    status         VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    remark         VARCHAR(255),
    operator       VARCHAR(64) NOT NULL DEFAULT 'system',
    request_id     VARCHAR(64),
    biz_time       TIMESTAMP,
    version        INT NOT NULL DEFAULT 0,
    deleted        BIGINT NOT NULL DEFAULT 0,
    create_by      BIGINT,
    create_time    TIMESTAMP,
    update_by      BIGINT,
    update_time    TIMESTAMP,
    CONSTRAINT uk_notify_recipient_staff UNIQUE (staff_no, deleted)
);
CREATE INDEX IF NOT EXISTS idx_notify_recipient_role ON t_notify_recipient (role_code, enabled, id);

-- 通知批次：一次业务事件一条；status 汇总该批次各通道结果。
-- (event_code, ticket_id) 唯一：事件重复消费不重复通知（手动重发走发送记录）。
-- status: SUCCESS 通道全部成功 / PARTIAL 部分成功 / FAILED 全部失败
CREATE TABLE IF NOT EXISTS t_notify_dispatch (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_code       VARCHAR(48) NOT NULL,
    ticket_id        BIGINT NOT NULL,
    ticket_no        VARCHAR(48),
    order_no         VARCHAR(48),
    session_code     VARCHAR(32),
    status           VARCHAR(16) NOT NULL,
    total_channels   INT NOT NULL DEFAULT 0,
    success_channels INT NOT NULL DEFAULT 0,
    fail_channels    INT NOT NULL DEFAULT 0,
    trigger_operator VARCHAR(64),
    request_id       VARCHAR(64),
    event_time       TIMESTAMP,
    create_time      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time      TIMESTAMP,
    CONSTRAINT uk_notify_dispatch_event_ticket UNIQUE (event_code, ticket_id)
);
CREATE INDEX IF NOT EXISTS idx_notify_dispatch_ticket ON t_notify_dispatch (ticket_no, id);
CREATE INDEX IF NOT EXISTS idx_notify_dispatch_status ON t_notify_dispatch (status, id);

-- 逐通道发送记录：每条 = 某事件经某通道发给某收件人的一次发送。
-- 渲染后标题/正文/变量集在此快照，模板后续改动与已发内容无关。
-- status: PENDING 待发 / SUCCESS 成功 / RETRYING 退避重试中 / FAILED 重试耗尽 / SKIPPED 不具备发送条件（如无邮箱）
CREATE TABLE IF NOT EXISTS t_notify_record (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dispatch_id      BIGINT NOT NULL,
    event_code       VARCHAR(48) NOT NULL,
    channel          VARCHAR(8) NOT NULL,
    template_id      BIGINT NOT NULL,
    template_version INT NOT NULL,
    recipient_id     BIGINT,
    recipient_name   VARCHAR(64) NOT NULL,
    recipient_address VARCHAR(128),
    ticket_no        VARCHAR(48),
    order_no         VARCHAR(48),
    session_code     VARCHAR(32),
    title_rendered   VARCHAR(255) NOT NULL,
    content_rendered CLOB NOT NULL,
    vars_snapshot    CLOB,
    message_id       VARCHAR(64),
    http_status      INT,
    status           VARCHAR(16) NOT NULL,
    retry_count      INT NOT NULL DEFAULT 0,
    max_retry        INT NOT NULL DEFAULT 2,
    next_retry_time  TIMESTAMP,
    last_error       VARCHAR(2000),
    operator         VARCHAR(64) NOT NULL DEFAULT 'system',
    request_id       VARCHAR(64),
    biz_time         TIMESTAMP,
    create_time      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    sent_time        TIMESTAMP,
    update_time      TIMESTAMP
);
-- 批次回查 / 重试扫描 / 统计与按票归档索引
CREATE INDEX IF NOT EXISTS idx_notify_rec_dispatch ON t_notify_record (dispatch_id);
CREATE INDEX IF NOT EXISTS idx_notify_rec_retry ON t_notify_record (status, next_retry_time);
CREATE INDEX IF NOT EXISTS idx_notify_rec_channel ON t_notify_record (channel, id);
CREATE INDEX IF NOT EXISTS idx_notify_rec_ticket ON t_notify_record (ticket_no, id);
CREATE INDEX IF NOT EXISTS idx_notify_rec_event ON t_notify_record (event_code, id);

-- 站内信箱：INBOX 通道发送成功即写一行；场务按 staff_no 查收。
CREATE TABLE IF NOT EXISTS t_inbox_message (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_no       VARCHAR(64) NOT NULL,
    recipient_name VARCHAR(64),
    title          VARCHAR(255) NOT NULL,
    content        CLOB NOT NULL,
    category       VARCHAR(48) NOT NULL DEFAULT 'TICKET_CHECK',
    biz_key        VARCHAR(128),
    read_flag      INT NOT NULL DEFAULT 0,
    read_time      TIMESTAMP,
    record_id      BIGINT,
    create_time    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_inbox_record UNIQUE (record_id)
);
-- 收件箱主查询：工号 + 已读位 + 时间倒序
CREATE INDEX IF NOT EXISTS idx_inbox_staff ON t_inbox_message (staff_no, read_flag, id);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('flyway-4', '检票关键节点通知场务：事件触发、模板变量渲染、站内信+邮件双通道、发送记录入库可查、失败重试2次、渲染快照隔离模板变更');
