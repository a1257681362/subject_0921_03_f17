-- =====================================================================
-- V7 增量：检票备注敏感词扫描（sensitive-1）
-- ---------------------------------------------------------------------
-- 背景：场馆手工台账错漏不少，检票备注（reason/取消原因等自由文本）入系统前
-- 先过一遍敏感词：DFA 算法扫描，全角半角/大小写/插缝干扰先归一再匹配；
-- 词库分两级——高危命中直接拦截本次操作，低危命中片段打码（*）后放行。
-- 每次命中留痕：被扫原文、命中的词与级别、原文命中片段、码点起止位置、
-- 处置结论（BLOCKED/MASKED）、操作人与请求号，事后可审计、可回查。
--
-- 表：
--   t_sensitive_word     分级敏感词库（ENABLED 生效 / DISABLED 停用；改库后热刷新 DFA）
--   t_sensitive_hit_log  命中留痕（逐词一行，只追加；原文与位置齐备）
--
-- 权限：敏感词管理仅 ADMIN（系统管理目录新增菜单/权限点 250~252）。
--
-- 并跑期约定：向旧台账 t_evops_schema_version 双写 flyway-7。
-- =====================================================================

-- 分级敏感词库：normalized_word 为归一形态（NFKC+小写+去干扰），同形唯一；
-- 重复入库时 HIGH 覆盖 LOW（构建 DFA 时同样高危优先）。
CREATE TABLE IF NOT EXISTS t_sensitive_word (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    word             VARCHAR(128) NOT NULL,
    normalized_word  VARCHAR(128) NOT NULL,
    -- HIGH 高危拦截 / LOW 低危打码
    level            VARCHAR(16)  NOT NULL,
    -- 词分类：FRAUD 诈骗/PORN 色情/GAMBLING 赌博/SCALPER 黄牛/ILLEGAL 违禁/AD 引流广告
    category         VARCHAR(32),
    -- ENABLED 计入 DFA / DISABLED 停用留档
    status           VARCHAR(16)  NOT NULL DEFAULT 'ENABLED',
    remark           VARCHAR(255),
    operator         VARCHAR(64)  NOT NULL DEFAULT 'system',
    request_id       VARCHAR(64),
    biz_time         TIMESTAMP,
    create_time      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time      TIMESTAMP,
    CONSTRAINT uk_sensitive_word_norm UNIQUE (normalized_word)
);
-- 生效词库装载：按状态+级别
CREATE INDEX IF NOT EXISTS idx_sensitive_word_status ON t_sensitive_word (status, level);

-- 命中留痕：逐词一行，只追加不修改。
-- 位置口径为被扫原文的 Unicode 码点半开区间 [start_cp, end_cp)
-- （全角/插缝干扰在归一时跳过，区间仍覆盖命中片段中的干扰符）。
CREATE TABLE IF NOT EXISTS t_sensitive_hit_log (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 场景：CHECK 检票 / REFUND 退票 / VOID 作废 / APPT_CANCEL 取消排期
    scene         VARCHAR(32)  NOT NULL,
    -- 业务定位：票号/预约号等
    biz_ref       VARCHAR(64),
    -- 被扫字段名（如 reason/cancelReason）
    field_name    VARCHAR(64)  NOT NULL,
    word_id       BIGINT,
    word          VARCHAR(128) NOT NULL,
    level         VARCHAR(16)  NOT NULL,
    -- 命中位置上的原文片段（观众实际输入的原样形态，含全角/干扰符）
    matched_text  VARCHAR(255) NOT NULL,
    start_cp      INT NOT NULL,
    end_cp        INT NOT NULL,
    -- 本次被扫字段完整原文（逐词冗余，按任一命中都能回查原文）
    original_text CLOB,
    -- 打码后的文本（BLOCKED 时为 NULL）
    masked_text   CLOB,
    -- BLOCKED 高危拦截 / MASKED 低危打码放行
    action        VARCHAR(16)  NOT NULL,
    operator      VARCHAR(64)  NOT NULL DEFAULT 'system',
    request_path  VARCHAR(255),
    request_id    VARCHAR(64),
    hit_time      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- 按时间审计 / 按词回查 / 按业务单回查 三条主路径
CREATE INDEX IF NOT EXISTS idx_senshit_time ON t_sensitive_hit_log (hit_time, id);
CREATE INDEX IF NOT EXISTS idx_senshit_word ON t_sensitive_hit_log (word, hit_time);
CREATE INDEX IF NOT EXISTS idx_senshit_biz  ON t_sensitive_hit_log (scene, biz_ref, hit_time);

