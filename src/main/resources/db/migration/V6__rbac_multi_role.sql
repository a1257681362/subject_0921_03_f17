-- =====================================================================
-- V6 增量：一人多岗 RBAC（rbac-1）
-- ---------------------------------------------------------------------
-- 整改要求（上个季度提出，排队至今）：
--   1) 权限模型支持一人多岗：一个账号可绑多个启用角色，角色叠加取【并集】
--      （绝不是交集）；接口权限码与菜单均按并集装配；
--   2) 菜单树按并集动态装配：登录后 GET /api/auth/menus 实时返回多岗菜单去重树；
--   3) 停用角色/取消授权即时收权：授权每请求按库内启用状态实时装载，
--      旧 JWT 不必重签、用户不必重登，下一请求即 403；
--   4) 越权访问统一拦截并记录：权限不足统一 403，逐笔落 t_rbac_deny_log 可审计。
--
-- 表：
--   t_rbac_role       角色（code 唯一；ACTIVE/DISABLED；builtin 禁删）
--   t_admin_user_role 用户-岗位多对多（一人多岗；仅 ACTIVE 角色计入授权）
--   t_rbac_menu       菜单/权限点树（DIR 目录 / MENU 菜单 / BUTTON 权限点）
--   t_rbac_role_menu  角色-菜单授权（角色拥有的菜单与权限点）
--   t_rbac_deny_log   越权访问审计（只追加，管理端分页查询）
--
-- 兼容：t_admin_user.role 单值列保留不动，降级为「主岗位」，继续供 JWT/脱敏
-- 白名单主角色等历史口径使用；真正的授权事实源是上面的关联表。
--
-- 注意执行时序：Flyway 先于 ApplicationRunner 播种。本脚本里的存量账号回填
-- 仅对「老库升级」有效；新库账号由 VenueSampleDataSeeder/NotifySampleDataSeeder/
-- RbacSampleDataSeeder 在迁移完成后播种时同步写 t_admin_user_role，两条路都幂等。
--
-- 并跑期约定：向旧台账 t_evops_schema_version 双写 flyway-6。
-- =====================================================================

-- 角色
CREATE TABLE IF NOT EXISTS t_rbac_role (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(64)  NOT NULL,
    name        VARCHAR(64)  NOT NULL,
    status      VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE', -- ACTIVE 启用 / DISABLED 停用（停用即时收权）
    builtin     INT NOT NULL DEFAULT 0,                 -- 1 内置角色：禁删、code 禁改
    remark      VARCHAR(255),
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_rbac_role_code UNIQUE (code)
);

-- 用户-岗位（一人多岗；授权只计 status=ACTIVE 的角色）
CREATE TABLE IF NOT EXISTS t_admin_user_role (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    CONSTRAINT uk_admin_user_role UNIQUE (user_id, role_id)
);
CREATE INDEX IF NOT EXISTS idx_user_role_role ON t_admin_user_role (role_id);
CREATE INDEX IF NOT EXISTS idx_user_role_user ON t_admin_user_role (user_id);

-- 菜单/权限点树：DIR 目录 / MENU 菜单（页面）/ BUTTON 按钮或纯权限点
CREATE TABLE IF NOT EXISTS t_rbac_menu (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id   BIGINT NOT NULL DEFAULT 0,
    type        VARCHAR(8)  NOT NULL,
    name        VARCHAR(64) NOT NULL,
    -- 权限码全局唯一（如 ticket:order:create）；DIR 可空
    permission  VARCHAR(96),
    path        VARCHAR(128),  -- 前端路由
    icon        VARCHAR(64),
    sort_no     INT NOT NULL DEFAULT 0,
    visible     INT NOT NULL DEFAULT 1,                 -- 1 出现在菜单树 / 0 仅作权限点下发
    status      VARCHAR(16) NOT NULL DEFAULT 'ENABLED', -- ENABLED / DISABLED（停用即收权）
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_rbac_menu_perm UNIQUE (permission)
);
CREATE INDEX IF NOT EXISTS idx_rbac_menu_parent ON t_rbac_menu (parent_id, sort_no);

-- 角色-菜单授权（覆盖式维护：整角色重写）
CREATE TABLE IF NOT EXISTS t_rbac_role_menu (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id BIGINT NOT NULL,
    menu_id BIGINT NOT NULL,
    CONSTRAINT uk_rbac_role_menu UNIQUE (role_id, menu_id)
);
CREATE INDEX IF NOT EXISTS idx_rbac_rolemenu_menu ON t_rbac_role_menu (menu_id);

-- 越权访问审计：只追加不修改
CREATE TABLE IF NOT EXISTS t_rbac_deny_log (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT NOT NULL,
    username            VARCHAR(64) NOT NULL,   -- 工号
    roles_csv           VARCHAR(512) NOT NULL,  -- 当时实际启用角色并集（CSV，按 code 排序）
    request_method      VARCHAR(8) NOT NULL,
    request_path        VARCHAR(255) NOT NULL,
    -- 注解要求的权限码（可能多个，CSV）
    required_permission VARCHAR(512) NOT NULL,
    client_ip           VARCHAR(64),
    request_id          VARCHAR(64),
    deny_time           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_denylog_user ON t_rbac_deny_log (username, deny_time, id);
CREATE INDEX IF NOT EXISTS idx_denylog_time ON t_rbac_deny_log (deny_time, id);

