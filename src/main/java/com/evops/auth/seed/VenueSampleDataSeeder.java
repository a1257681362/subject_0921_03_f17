    // ==================== 行组装 ====================

    private void insertOrder(long id, String orderNo, long sessionId, int count, int amount,
                             String status, LocalDateTime bizTime, String requestId) {
        jdbc.update("INSERT INTO t_sale_order "
                        + "(id, order_no, session_id, ticket_count, total_amount, status, "
                        + "operator, request_id, biz_time, version, deleted, create_by, create_time, update_by, update_time) "
                        + "VALUES (?,?,?,?,?,?,?,?,?,0,0,2,?,2,?)",
                id, orderNo, sessionId, count, amount, status, "box_office01", requestId, bizTime, bizTime, bizTime);
    }

    private void addTicket(List<Object[]> rows, long id, String ticketNo, long orderId, long sessionId,
                           long seatId, int price, String status, LocalDateTime bizTime, String requestId) {
        rows.add(new Object[]{id, ticketNo, orderId, sessionId, seatId, price, status,
                "box_office01", requestId, bizTime, bizTime, bizTime});
    }

    private void addOccupy(List<Object[]> rows, long sessionId, long seatId, long ticketId,
                           long orderId, LocalDateTime createTime) {
        rows.add(new Object[]{sessionId, seatId, ticketId, orderId, createTime});
    }

    private long addIssueFlows(List<Object[]> flows, long startId, LocalDateTime bizTime,
                               long orderId, long[] ticketIds, String requestId) {
        return addIssueFlows(flows, startId, bizTime, orderId, ticketIds, 1L, requestId);
    }

    private long addIssueFlows(List<Object[]> flows, long startId, LocalDateTime bizTime,
                               long orderId, long[] ticketIds, long sessionId, String requestId) {
        long id = startId;
        for (long ticketId : ticketIds) {
            addFlow(flows, id++, ticketId, orderId, sessionId, "ISSUE", 0, null, null, "SOLD",
                    "售票出票", "box_office01", requestId, bizTime);
        }
        return id;
    }

    private void addFlow(List<Object[]> rows, long id, long ticketId, long orderId, long sessionId,
                         String type, int reverseFlag, Long originId, String fromStatus, String toStatus,
                         String reason, String operator, String requestId, LocalDateTime bizTime) {
        rows.add(new Object[]{id, ticketId, orderId, sessionId, type, reverseFlag, originId,
                fromStatus, toStatus, reason, operator, requestId, bizTime, bizTime});
    }
